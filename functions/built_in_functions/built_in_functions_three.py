# abs()
print(abs(100))
print(abs(-100))
print(abs(110.50))
print(abs(-110.50))

# pow()
print(pow(2, 2)) # 2 * 2
print(pow(2, 3)) # 2 * 2 * 2
print(pow(3, 2)) # 3 * 3
print(pow(4, 2)) # 4 * 4

#  min()
a = [23, 34, -23, -19, -134, 213]
print(min(a))
print(min(("x", "y", "z")))

#  slice()
b = [23, 34, -23, -19, -134, 213]
print(b[0:5:1])
print(b[slice(0, 5, 1)])
