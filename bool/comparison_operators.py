# Equal
print("Equality operator")
print(100 == 100)
print(100 == 100.00) # -> prints True
print(100 == 200)

# Not equal
print("=" * 50)
print("not equal")
print(100 != 100)
print(100 != 200)

# greater than
print("=" * 50)
print("Greater than")
print(100 > 100)
print(100 > 200)

# smaller than
print("=" * 50)
print("smaller than")
print(100 < 100)
print(100 < 200)

# greater than or equal
print("=" * 50)
print("greater than or equal")
print(100 >= 100)
print(100 >= 200)

# smaller than or equal
print("=" * 50)
print("smaller than or equal")
print(100 <= 100)
print(100 <= 200)